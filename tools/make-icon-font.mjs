/* Builds the icon font the buttons use, from Phosphor (MIT), cut down to the
   icons ivx/docs actually shows: a few kilobytes instead of 150 per weight.
   Run with: node tools/make-icon-font.mjs   (after changing the lists below)

   Writes src/icons/phosphor.woff2 and phosphor-fill.woff2, and icons.css,
   which gives each icon a class: <i class="icon icon-plus"></i>, and
   `icon fill icon-star` for the filled one. */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import subsetFont from 'subset-font';

/** Outline icons, by Phosphor name. */
const ICONS = [
  // Tasks
  'plus', 'list-bullets', 'kanban', 'gear-six', 'sidebar-simple', 'calendar-dots', 'star',
  'list-checks', 'archive', 'trash', 'pencil-simple', 'x', 'check', 'arrow-counter-clockwise',
  'qr-code', 'scan', 'copy', 'link-break', 'cloud-arrow-up', 'cloud-arrow-down',
  'download-simple', 'upload-simple', 'sign-in', 'sign-out', 'bell', 'broom', 'caret-right',
  'caret-down', 'repeat', 'calendar-blank', 'clock',
  // Sign, Verify, Merge
  'folder-open', 'arrows-merge', 'signature', 'eraser', 'magnifying-glass', 'arrow-up', 'arrow-down',
  'file-magnifying-glass',
];

/** Icons that also come filled, for an "on" state: a starred star. */
const FILLED = ['star'];

const root = new URL('../node_modules/@phosphor-icons/web/src/', import.meta.url);
const out = new URL('../src/icons/', import.meta.url);

function codepoints(weight, names) {
  const css = readFileSync(new URL(`${weight}/style.css`, root), 'utf8');
  const prefix = weight === 'regular' ? '.ph' : `.ph-${weight}`;
  return names.map(name => {
    const m = css.match(new RegExp(`\\${prefix}\\.ph-${name}:before\\s*\\{\\s*content:\\s*"\\\\([0-9a-f]+)"`));
    if (!m) throw new Error(`Phosphor has no ${weight} icon called ${name}`);
    return [name, parseInt(m[1], 16)];
  });
}

async function cut(weight, file, names) {
  const points = codepoints(weight, names);
  const font = readFileSync(new URL(`${weight}/Phosphor${weight === 'regular' ? '' : `-${weight[0].toUpperCase()}${weight.slice(1)}`}.woff2`, root));
  const text = points.map(([, cp]) => String.fromCodePoint(cp)).join('');
  const woff2 = await subsetFont(font, text, { targetFormat: 'woff2' });
  writeFileSync(new URL(file, out), woff2);
  console.log(`  ${file}: ${names.length} icons, ${woff2.length} bytes`);
  return points;
}

mkdirSync(out, { recursive: true });
const regular = await cut('regular', 'phosphor.woff2', ICONS);
await cut('fill', 'phosphor-fill.woff2', FILLED);

const hex = cp => cp.toString(16);
writeFileSync(new URL('icons.css', out), `/* Generated by tools/make-icon-font.mjs from Phosphor Icons (MIT,
   https://phosphoricons.com). Edit the lists there, not this file. */

@font-face {
  font-family: 'ivx-icons';
  src: url('./phosphor.woff2') format('woff2');
  font-display: block;
}

@font-face {
  font-family: 'ivx-icons-fill';
  src: url('./phosphor-fill.woff2') format('woff2');
  font-display: block;
}

.icon {
  display: inline-block;
  font-family: 'ivx-icons';
  font-style: normal;
  font-weight: normal;
  line-height: 1;
  font-size: 1.15em;
  vertical-align: -0.2em;
  speak: never;
  -webkit-font-smoothing: antialiased;
}

.icon.fill { font-family: 'ivx-icons-fill'; }

${regular.map(([name, cp]) => `.icon-${name}::before { content: '\\${hex(cp)}'; }`).join('\n')}
`);
console.log('  icons.css');
